class DeathSave {

  constructor(container) {
    this.cbs = [...container.querySelectorAll('.death-save-checkbox')];
    this.cbs = this.cbs.map((cb) => {
      cb = new Checkbox(cb);
      cb.maxValue = 1;
      cb.clickListeners.push((box) => {
        var ind = this.cbs.indexOf(box);
        if (box.getValue() > 0)
          this.setValue(ind + 1);
        else
          this.setValue(ind);
      });
      return cb;
    });
    this.setValue(0);
  }

  setValue(value) {
    for (var i = 0; i < this.cbs.length; i++) {
      if (i < value)
        this.cbs[i].setValue(1);
      else
        this.cbs[i].setValue(0);
    }
  }

  getValue() {
    for (var i = this.cbs.length - 1; i >= 0; i--) {
      if (this.cbs[i].getValue() > 0)
        return i + 1;
    }
    return 0;
  }

}

