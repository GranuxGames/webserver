class Checkbox {

  constructor(element = null) {
    if (element == null) {
      this.element = document.createElement('img');
      this.element.classList.add('checkbox');
    } else {
      this.element = element;
    }
    this.element.addEventListener('click', () => {
      this.cycle();
      this.clickListeners.forEach((listener) => {
        listener(this);
      });
    });
    this.setValue(0);
    this.maxValue = 2;
    this.clickListeners = [];
  }

  cycle() {
    this.setValue((this.getValue() + 1) % (this.maxValue + 1));
  }

  setValue(value) {
    if (value != 1 && this.element.classList.contains('checked'))
      this.element.classList.remove('checked');
    else if (value == 1 && this.maxValue >= 1)
      this.element.classList.add('checked');
    if (value != 2 && this.element.classList.contains('double-checked'))
      this.element.classList.remove('double-checked')
    else if (value == 2 && this.maxValue >= 2)
      this.element.classList.add('double-checked');
  }

  getValue() {
    if (this.element.classList.contains('checked'))
      return 1;
    if (this.element.classList.contains('double-checked'))
      return 2;
    return 0;
  }

}

class Zoom {

  constructor(container) {
    this.container = container;
    this.zoom = 0;
    container.querySelector('.zoom-dec').addEventListener('click', () => {
      this.setZoom(this.zoom - 1);
    })
    container.querySelector('.zoom-inc').addEventListener('click', () => {
      this.setZoom(this.zoom + 1);
    });
    this.setZoom(0);
  }

  setZoom(zoom) {
    this.zoom = zoom;
    this.container.style.setProperty('--font-scale', Math.pow(1.25, this.zoom));
  }

}

class ImageContainer {

  constructor(container) {
    this.element = container;
    this.clear();
  }

  getValue() {
    return this.element.style.backgroundImage;
  }

  setValue(value) {
    this.element.style.backgroundImage = value;
  }

  clear() {
    this.element.style.backgroundImage = 'none';
  }

}

